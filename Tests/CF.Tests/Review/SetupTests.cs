    public void InitWritesOnlyRecognisedHooks(string? hooksFolder, string? script, string? prefix, string suffix, string? wrapper = null, string? reason = null)
    {
        using var harness = new ReviewHarness();
        var root = harness.RepositoryFolder;
        var configured = hooksFolder == null ? null : Path.GetFullPath(Path.Combine(root, hooksFolder));
        var active = Path.Combine(configured ?? Path.Combine(root, ".git", "hooks"), "pre-push");
        var target = active;
        if(hooksFolder == ".husky/_")
        {
            target = Path.Combine(root, ".husky", "pre-push");
            if(wrapper != null)
            {
                Directory.CreateDirectory(Path.GetDirectoryName(active)!);
                File.WriteAllText(active, wrapper);
            }
        }

        if(script != null)
        {
            Directory.CreateDirectory(Path.GetDirectoryName(target)!);
            File.WriteAllText(target, script);
        }

        var service = Service(harness, configured);
        var result = Init(harness, service, "init");
        Assert.Equal(ExitCode.Passed, result.ExitCode);
        var expected = prefix == null ? script : prefix + HookLine.PrePush + "\n" + suffix;
        Assert.Equal(expected, File.ReadAllText(target));
        if(hooksFolder == ".husky/_" && reason != null)
        {
            Assert.Equal(wrapper != null, File.Exists(active));
            if(wrapper != null)
                Assert.Equal(wrapper, File.ReadAllText(active));

            File.WriteAllText(target, HookLine.PrePush + "\n");
            target = active;
        }

        Assert.Contains(target, result.Output, StringComparison.Ordinal);
        if(prefix == null)
        {
            if(reason == "lefthook.yml")
                Assert.DoesNotContain(HookLine.PrePush, result.Output, StringComparison.Ordinal);
            else
                Assert.Contains(HookLine.PrePush, result.Output, StringComparison.Ordinal);
            if(reason != null)
            {
                Assert.Contains(reason, result.Output, StringComparison.Ordinal);
                var git = new DoctorGitStub(root) { HooksFolder = configured };
                var machine = new DoctorMachineStub("commitfence");
                var context = new DoctorContext(git.Repository, "commitfence", FixedProduct.ProgramVersion, machine, git);
                var check = new PrePushDoctorCheck(git, new SystemFileSystem()).Run(context);
                Assert.Equal(DoctorOutcome.Fails, check.Outcome);
                Assert.Null(check.Fix?.Addition);
                Assert.Contains(reason, check.Fix!.Text.ToString(), StringComparison.Ordinal);
            }

            return;
        }

        var second = Init(harness, service, "init");
        Assert.Contains("already contains", second.Output, StringComparison.Ordinal);
        Assert.Equal(expected, File.ReadAllText(target));

        if(script == null && !OperatingSystem.IsWindows())
            Assert.True(File.GetUnixFileMode(target).HasFlag(UnixFileMode.UserExecute));
    }

    [Fact]
    public void InitMakesAnEditedHookExecutableAndReportsAnUnchangedInactiveHook()
    {
        Assert.SkipUnless(OperatingSystem.IsLinux() || OperatingSystem.IsMacOS(), "Git for Windows does not use Unix file modes.");
        if(OperatingSystem.IsWindows())
            return;

        using var harness = new ReviewHarness();
        var target = Path.Combine(harness.RepositoryFolder, ".git", "hooks", "pre-commit");
        Directory.CreateDirectory(Path.GetDirectoryName(target)!);
        File.WriteAllText(target, "#!/bin/sh\necho test\n");
        const UnixFileMode mode = UnixFileMode.UserRead | UnixFileMode.UserWrite;
        File.SetUnixFileMode(target, mode);
        var service = Service(harness, null);

        var edited = Init(harness, service, "init", "--hook", "pre-commit");

        Assert.Equal(ExitCode.Passed, edited.ExitCode);
        Assert.Contains("Made", edited.Output, StringComparison.Ordinal);
        Assert.Contains("executable", edited.Output, StringComparison.Ordinal);
        Assert.Equal(mode | UnixFileMode.UserExecute, File.GetUnixFileMode(target));
        var installed = File.ReadAllBytes(target);
        File.SetUnixFileMode(target, mode);

        var unchanged = Init(harness, service, "init", "--hook", "pre-commit");

        Assert.Equal(ExitCode.Passed, unchanged.ExitCode);
        Assert.Contains("inactive because it is not executable", unchanged.Output, StringComparison.Ordinal);
        Assert.Equal(mode, File.GetUnixFileMode(target));
        Assert.Equal(installed, File.ReadAllBytes(target));
    }

    [Fact]
    public void InitInsertsAnLfLineWithoutChangingTheBytesAroundIt()
    {
        using var harness = new ReviewHarness();
        var hooks = Path.Combine(harness.RepositoryFolder, ".husky");
        Directory.CreateDirectory(hooks);
        var target = Path.Combine(hooks, "pre-push");
        const string before = "#!/bin/sh\n# café\r\n\n";
        const string after = "printf '%s' 'café'\r\n# no final newline";
        File.WriteAllBytes(target, [.. Encoding.UTF8.GetBytes(before), .. Encoding.UTF8.GetBytes(after)]);

        var result = Init(harness, Service(harness, hooks), "init");

        Assert.Equal(ExitCode.Passed, result.ExitCode);
        Assert.Equal(Encoding.UTF8.GetBytes(before + HookLine.PrePush + "\n" + after), File.ReadAllBytes(target));
    }

    [Fact]
    public void InitPrintsNativePathsForSettingsAndHooks()
    {
        using var harness = new ReviewHarness();
        var root = harness.RepositoryFolder;
        var hooks = Path.Combine(root, ".git", "hooks");
        Directory.CreateDirectory(hooks);
        var hook = Path.Combine(hooks, "pre-push");
        var settings = Path.Combine(root, "commitfence.json");
        const string shell = "#!/bin/sh\necho test\n";
        File.WriteAllText(hook, shell);
        var service = Service(harness, hooks.Replace(Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar));

        var preview = Init(harness, service, "init", "--print");
        Assert.Equal(ExitCode.Passed, preview.ExitCode);
        Assert.Contains($"Would write {settings},", preview.Output, StringComparison.Ordinal);
        Assert.Contains($"Would add this line to {hook} at line 2:", preview.Output, StringComparison.Ordinal);
        Assert.Equal(shell, File.ReadAllText(hook));
        Assert.False(File.Exists(settings));

        var added = Init(harness, service, "init");
        Assert.Equal(ExitCode.Passed, added.ExitCode);
        Assert.Contains($"Added the CommitFence line to {hook} at line 2.", added.Output, StringComparison.Ordinal);

        File.WriteAllText(hook, "#!/usr/bin/env node\nprocess.exit(0);\n");
        var manual = Init(harness, service, "init");
        Assert.Equal(ExitCode.Passed, manual.ExitCode);
        Assert.Contains($"Add this line as the first command of {hook}:", manual.Output, StringComparison.Ordinal);
    }

