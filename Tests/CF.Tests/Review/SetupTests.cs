    [Theory]
    [InlineData(false, "the folder is not in a Git repository", "Open a Git repository, then try again.")]
    [InlineData(true, "a folder named commitfence.json already exists there", "Move or rename the commitfence.json folder, then try again.")]
    public void SettingsFailuresReportTheReasonAndHowToRecover(bool inRepository, string reason, string remedy)
    {
        using var harness = new ReviewHarness();
        var folder = inRepository ? harness.RepositoryFolder : harness.Scratch;
        var settingsPath = Path.Combine(folder, "commitfence.json");
        if(inRepository)
            Directory.CreateDirectory(settingsPath);

        var result = Service(harness, null).StartSettings(folder);

        Assert.True(result.Failed);
        Assert.Collection(result.Lines,
            line => Assert.Equal($"Could not write commitfence.json: {reason}.", line),
            line => Assert.Equal($"Nothing was written. {remedy}", line));
        Assert.Equal(inRepository, Directory.Exists(settingsPath));
    }

    [Fact]
    public void AReadOnlyHookKeepsItsContentsAndNamesThePreviewedLine()
    {
        using var harness = new ReviewHarness();
        var root = harness.RepositoryFolder;
        var git = new DoctorGitStub(root);
        var target = git.FindHook(git.Repository, "pre-push");
        Directory.CreateDirectory(Path.GetDirectoryName(target)!);
        const string original = "#!/bin/sh\n# Run a check\n\necho test\n";
        File.WriteAllText(target, original);
        var attributes = File.GetAttributes(target);
        File.SetAttributes(target, attributes | FileAttributes.ReadOnly);
        try
        {
            var context = new DoctorContext(git.Repository, "commitfence", FixedProduct.ProgramVersion, new DoctorMachineStub("commitfence"), git);
            var addition = Assert.IsType<HookAddition>(new PrePushDoctorCheck(git, new SystemFileSystem()).Run(context).Fix?.Addition);
            var result = Service(harness, null).AddHookLine(root, addition);

            Assert.Equal(4, addition.After.Line);
            Assert.True(result.Failed);
            Assert.StartsWith("Could not write", result.Lines[0], StringComparison.Ordinal);
            Assert.Contains("Nothing was changed.", result.Lines[1], StringComparison.Ordinal);
            Assert.Contains("add it by hand as line 4", result.Lines[1], StringComparison.Ordinal);
            Assert.Equal(original, File.ReadAllText(target));
        }
        finally
        {
            File.SetAttributes(target, attributes);
        }
    }

    private static SetupService Service(ReviewHarness harness, string? hooksFolder)
    {
        return new SetupService(new RecordingGitSettings(), new RecordingUserPath(), harness.Fake, new SystemFileSystem(),
            new DoctorGitStub(harness.RepositoryFolder) { HooksFolder = hooksFolder });
    }

    private static CommandOutcome Init(ReviewHarness harness, ISetupService service, params string[] args)
    {
        using var output = new StringWriter();
        using var error = new StringWriter();
        var environment = new CommandEnvironment(harness.RepositoryFolder, "/program", "/program/commitfence", TextReader.Null, output, error, false);
        var code = new CommandRunner(null!, null!, null!, service, null!, environment).Run(args);
        return new CommandOutcome(code, output.ToString(), error.ToString());
    }

    [Fact]
    public void InitCreatesStarterRulesAndPreservesTeamEditsOnRepeat()
    {
        using(var harness = new ReviewHarness())
        {
            var files = new SystemFileSystem();
            var service = new SetupService(new RecordingGitSettings(), new RecordingUserPath(), harness.Fake, files, new DoctorGitStub(harness.RepositoryFolder));
            var rulesPath = Path.Combine(harness.RepositoryFolder, "commitfence.json");

            var first = service.Init(harness.RepositoryFolder);

            Assert.False(first.Failed);
            Assert.Contains(HookLine.PrePush, File.ReadAllText(Path.Combine(harness.RepositoryFolder, ".git", "hooks", "pre-push")), StringComparison.Ordinal);
            var starter = new SettingsFile(files, new SettingsReader(harness.Languages)).Read(rulesPath);
            Assert.Empty(starter.ActiveRules);

            var teamRules = ReviewSources.Settings(ReviewSources.Team010);
            File.WriteAllText(rulesPath, teamRules);
            var second = service.Init(harness.RepositoryFolder);

            Assert.False(second.Failed);
            Assert.Equal(teamRules, File.ReadAllText(rulesPath));
        }
    }
